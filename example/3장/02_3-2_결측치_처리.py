# --- 실행 준비 (교재에서는 앞 절에서 이미 실행한 코드) --------------------
import pandas as pd
import numpy as np
df = pd.read_csv("data/battery_process_data.csv")
df["건조로_1구간_온도"] = df["건조로_1구간_온도"].replace(9999, np.nan)
df = df.fillna(df.median(numeric_only=True))   # 3.7절 clean_data() 규약

# --------------------------------------------------------------------
# [결측치의 탐지]
# --------------------------------------------------------------------
print(df.isna().sum())

# 교재 실행 결과 ------------------------------------------------------
#   Lot_ID            0
#   믹싱_RPM            0
#   믹싱_온도             5
#   코팅_토출압력           0
#   건조로_1구간_온도        0
#   프레스_압력            0
#   프레스_Gap           0
#   최종_용량_mAh         0
#   전극_면저항_mOhmcm2    0
#   불량_여부             0
#   dtype: int64

# --------------------------------------------------------------------
# [결측치의 탐지]
# --------------------------------------------------------------------
print(df[df['믹싱_온도'].isna()][['Lot_ID', '믹싱_RPM', '믹싱_온도', '불량_여부']])

# 교재 실행 결과 ------------------------------------------------------
#        Lot_ID  믹싱_RPM  믹싱_온도  불량_여부
#   21   L25021    1696    NaN      0
#   149  L25149    1763    NaN      0
#   434  L25434    1824    NaN      0
#   692  L25692    1826    NaN      0
#   945  L25945    1722    NaN      0

# --------------------------------------------------------------------
# [실습 — 믹싱_온도 결측 5건 처리]
# --------------------------------------------------------------------
mean_v = df['믹싱_온도'].mean()
med_v = df['믹싱_온도'].median()
print("평균:", round(mean_v, 3), " 중앙값:", round(med_v, 3))

print("불량_여부 그룹별 믹싱_온도 평균:")
print(df.groupby('불량_여부')['믹싱_온도'].mean().round(3))

# 교재 실행 결과 ------------------------------------------------------
#   평균: 24.879  중앙값: 24.9
#   불량_여부 그룹별 믹싱_온도 평균:
#   불량_여부
#   0    24.871
#   1    25.274
#   Name: 믹싱_온도, dtype: float64

# --------------------------------------------------------------------
# [실습 — 믹싱_온도 결측 5건 처리]
# --------------------------------------------------------------------
df['믹싱_온도'] = df['믹싱_온도'].fillna(med_v)
print("결측치 개수(처리 후):", df['믹싱_온도'].isna().sum())

# 교재 실행 결과 ------------------------------------------------------
#   결측치 개수(처리 후): 0

