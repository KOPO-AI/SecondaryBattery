# --- 실행 준비 (교재에서는 앞 절에서 이미 실행한 코드) --------------------
import pandas as pd
import numpy as np
df = pd.read_csv("data/battery_process_data.csv")
df["건조로_1구간_온도"] = df["건조로_1구간_온도"].replace(9999, np.nan)
df = df.fillna(df.median(numeric_only=True))   # 3.7절 clean_data() 규약

# --------------------------------------------------------------------
# [중복 데이터 — duplicated]
# --------------------------------------------------------------------
print("완전 중복 행:", df.duplicated().sum())
print("Lot_ID 중복:", df.duplicated(subset='Lot_ID').sum())

# 교재 실행 결과 ------------------------------------------------------
#   완전 중복 행: 0
#   Lot_ID 중복: 0

# --------------------------------------------------------------------
# [형변환 — astype과 숫자 열이 문자가 되는 사고]
# --------------------------------------------------------------------
print(df.dtypes)
df['불량_여부'] = df['불량_여부'].astype('int8')
print("변환 후 불량_여부:", df['불량_여부'].dtype)

