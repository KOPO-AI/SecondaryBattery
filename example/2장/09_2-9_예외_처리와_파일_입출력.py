# --------------------------------------------------------------------
values = ["3607.4", "3603.1", "오류", "3598.3"]
clean = []
for v in values:
    try:
        clean.append(float(v))
    except ValueError:
        print(f"숫자로 바꿀 수 없는 값 발견: {v!r} → 건너뜀")
print(clean)

# 교재 실행 결과 ------------------------------------------------------
