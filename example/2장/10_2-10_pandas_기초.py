# --------------------------------------------------------------------
# [새 열 계산하기 `필수`]
# --------------------------------------------------------------------
df["용량_면저항_비"] = df["최종_용량_mAh"] / df["전극_면저항_mOhmcm2"]
print(df[["Lot_ID", "최종_용량_mAh", "전극_면저항_mOhmcm2", "용량_면저항_비"]].head(3).round(3))

# 교재 실행 결과 ------------------------------------------------------
