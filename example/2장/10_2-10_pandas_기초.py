# --------------------------------------------------------------------
# [행 필터링 — 불량 로트만 추출하기 `필수`]
# --------------------------------------------------------------------
defect = df[df["불량_여부"] == 1]
print(defect.shape)
print(defect[["Lot_ID", "최종_용량_mAh", "전극_면저항_mOhmcm2"]].head())
print(f"전체 불량률: {df['불량_여부'].mean() * 100:.2f}%")
cond = (df["프레스_압력"] > 48) & (df["불량_여부"] == 1)   # AND는 &, 조건마다 괄호
print(df[cond].shape[0], "개 로트")

# 교재 실행 결과 ------------------------------------------------------
#   (19, 10)
