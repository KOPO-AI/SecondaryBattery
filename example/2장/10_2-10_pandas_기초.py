# --------------------------------------------------------------------
# [열 선택 `필수`]
# --------------------------------------------------------------------
print(df["최종_용량_mAh"].head(3))                          # 한 열 → Series
print(df[["Lot_ID", "최종_용량_mAh", "불량_여부"]].head(3))   # 여러 열 → DataFrame

# 교재 실행 결과 ------------------------------------------------------
#   0    3607.4
#   1    3603.1
#   2    3635.7
#   Name: 최종_용량_mAh, dtype: float64
